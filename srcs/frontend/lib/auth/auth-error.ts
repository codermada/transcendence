export function getAuthErrorMessage(error: unknown): string {
  if (!error) {
    return "Something went wrong.";
  }

  if (
    typeof error === "object" &&
    error !== null &&
    "message" in error &&
    typeof error.message === "string"
  ) {
    return error.message;
  }

  return "Something went wrong. Please try again.";
}
